import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const facade = read("src/store/useTaskStore.ts");
const moduleRoot = "src/store/task-center";
const contracts = read(`${moduleRoot}/contracts.ts`);
const model = read(`${moduleRoot}/model.ts`);
const lifecycle = read(`${moduleRoot}/lifecycleActions.ts`);
const persistent = read(`${moduleRoot}/persistentAgentActions.ts`);
const factory = read(`${moduleRoot}/createTaskStore.ts`);
if (!facade.includes("createTaskStore") || !facade.includes("WorkbenchTask")) throw new Error("Task store facade must retain its factory and public contracts.");
for (const source of [contracts, model, lifecycle, persistent, factory]) if (source.includes("useTaskStore")) throw new Error("Task store owners cannot import the compatibility facade.");
if (contracts.includes("zustand" ) && !contracts.includes("StoreApi")) throw new Error("Task contracts must not own runtime composition.");
if (!model.includes("trimFinishedTaskHistory") || !model.includes("completeTask")) throw new Error("Task model must own history retention and completion transforms.");
if (!lifecycle.includes("startTask") || !lifecycle.includes("clearFinished") || lifecycle.includes("replacePersistentAgentTasks")) throw new Error("Task lifecycle owner must not absorb persistent-agent hydration.");
if (!persistent.includes("replacePersistentAgentTasks") || !persistent.includes("activeLocalTasks")) throw new Error("Persistent-agent owner must preserve late-hydration protection.");
if (!factory.includes("createTaskLifecycleActions") || !factory.includes("createPersistentAgentTaskActions")) throw new Error("Task store factory must compose lifecycle and persistence owners.");
console.log("Task store boundaries verified: contracts, pure task model, lifecycle actions, and persistent-agent hydration are explicit.");
