// Deterministic, offline projection of the same character readings used by the
// frontend. No phrase/polyphonic expansion and no runtime JavaScript dependency.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {pinyin} from 'pinyin-pro';
const source='node_modules/pinyin-pro';
const pkg=JSON.parse(fs.readFileSync(`${source}/package.json`,'utf8'));
assert.equal(pkg.version,'3.28.2');
const sha=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const pages=new Map();
let readings=0;
for(let cp=0;cp<=0x10ffff;cp++){
 const ch=String.fromCodePoint(cp);
 if(!/\p{Script=Han}/u.test(ch))continue;
 const value=pinyin(ch,{pattern:'first',toneType:'none'});
 if(!/^[a-z]$/u.test(value))continue;
 const page=cp>>>8;
 if(!pages.has(page))pages.set(page,Array(256).fill('.'));
 pages.get(page)[cp&255]=value;readings++;
}
const output='vendor/sql-lsp/src/identifier_search/pinyin_data.rs';
const lines=[
 '// Generated by scripts/generate-lsp-pinyin-initials.mjs; do not edit.',
 '// pinyin-pro 3.28.2, Copyright (c) 2022-present zh-lx, MIT.',
 '// License: PINYIN-LICENSE.txt. One default reading per character.',
 `// Source dist/index.mjs SHA-256: ${sha(`${source}/dist/index.mjs`)}`,
 `// ${readings} readings, ${pages.size} indexed pages; dots mark missing readings.`,
 '#[rustfmt::skip]',
 'pub(super) static PAGES: &[(u32, &[u8])] = &[',
 ...[...pages].map(([page,data])=>`    (0x${page.toString(16)}, b"${data.join('')}"),`),
 '];','',
];
const bytes=lines.join('\n');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(output,'utf8').replaceAll('\r\n','\n'),bytes,'regenerate pinyin table');
else{
 fs.mkdirSync('vendor/sql-lsp/src/identifier_search',{recursive:true});
 fs.writeFileSync(output,bytes);
 fs.copyFileSync(`${source}/LICENSE`,'vendor/sql-lsp/PINYIN-LICENSE.txt');
}
console.log(JSON.stringify({version:pkg.version,readings,pages:pages.size,sha256:createHash('sha256').update(bytes).digest('hex')}));
