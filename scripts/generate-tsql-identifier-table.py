"""Regenerate the checked-in BMP L*/Nd snapshot; not a build dependency."""
import argparse
import hashlib
from pathlib import Path
import unicodedata

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
ucd = unicodedata.ucd_3_2_0
assert ucd.unidata_version == '3.2.0'
points = [point for point in range(0x10000)
          if ucd.category(chr(point)).startswith('L') or ucd.category(chr(point)) == 'Nd']
ranges = []
for point in points:
    if ranges and point == ranges[-1][1] + 1:
        ranges[-1][1] = point
    else:
        ranges.append([point, point])
assert len(points) == 45838 and len(ranges) == 287
source = '''//! Generated by scripts/generate-tsql-identifier-table.py from Python's
//! immutable unicodedata.ucd_3_2_0 snapshot. BMP categories L* and Nd only.
//! Unicode data: https://www.unicode.org/Public/3.2-Update/UnicodeData-3.2.0.txt
//! Copyright Unicode, Inc.; see UNICODE-LICENSE.txt in this crate.
pub(crate) const BMP_LETTERS_AND_DECIMALS: &[(u16, u16)] = &[
'''
source += ''.join(f'    (0x{start:04X}, 0x{end:04X}),\n' for start, end in ranges)
source += '];\n'
target = Path(__file__).resolve().parents[1] / 'vendor/sql-lsp/src/tsql_identifier_table.rs'
if args.check:
    assert target.read_bytes() == source.encode('utf-8'), 'Unicode table drift; regenerate and review'
else:
    target.write_bytes(source.encode('utf-8'))
print(f'Unicode 3.2.0: {len(points)} BMP letters/decimal digits, {len(ranges)} ranges; '
      f'SHA-256 {hashlib.sha256(source.encode()).hexdigest()}')
