pub fn redis_capabilities() -> DatabaseCapabilities {
    REDIS_SPEC.capabilities()
}

pub fn elasticsearch_capabilities() -> DatabaseCapabilities {
    ELASTICSEARCH_SPEC.capabilities()
}

pub fn mongodb_capabilities() -> DatabaseCapabilities {
    MONGODB_SPEC.capabilities()
}

pub fn all_database_capabilities() -> Vec<DatabaseCapabilities> {
    DATABASE_SPECS
        .iter()
        .map(|spec| spec.capabilities())
        .collect()
}

pub fn database_spec_for_driver(driver: &str) -> Option<&'static DatabaseSpec> {
    DATABASE_SPECS
        .iter()
        .copied()
        .find(|spec| spec.matches_driver(driver))
}

pub fn canonical_driver_name(driver: &str) -> Option<&'static str> {
    database_spec_for_driver(driver).map(|spec| spec.driver)
}

pub fn database_capabilities_for_driver(driver: &str) -> Result<DatabaseCapabilities> {
    database_spec_for_driver(driver)
        .map(DatabaseSpec::capabilities)
        .ok_or_else(|| anyhow!("Unsupported database driver: {}", driver.trim()))
}

/// Presentation identity is intentionally independent from the canonical
/// runtime/capability identity. A protocol-compatible product must continue
/// to tell the user what they selected even when the Host executes through a
/// conservative bundled PostgreSQL, MySQL, or Elasticsearch implementation.
pub fn database_display_name_for_driver(driver: &str) -> String {
    let requested = driver.trim();
    match requested.to_ascii_lowercase().as_str() {
        "cockroach" | "cockroachdb" => "CockroachDB".to_string(),
        "easysearch" => "Easysearch".to_string(),
        "gaussdb" => "GaussDB".to_string(),
        "greenplum" => "Greenplum".to_string(),
        "mariadb" => "MariaDB".to_string(),
        "opengauss" => "openGauss".to_string(),
        "redshift" => "Amazon Redshift".to_string(),
        "tidb" => "TiDB".to_string(),
        "timescaledb" => "TimescaleDB".to_string(),
        "yugabyte" | "yugabytedb" => "YugabyteDB".to_string(),
        _ => database_spec_for_driver(requested)
            .map(|spec| spec.display_name.to_string())
            .unwrap_or_else(|| requested.to_string()),
    }
}
